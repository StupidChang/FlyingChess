    private function createReferenceTemplate(
        string $name,
        string $description,
        string $referenceImage,
        array $squares,
        array $wheel,
    ): void {
        $board = Board::updateOrCreate(
            ['name' => $name, 'is_template' => true],
            [
                'description' => $description,
                'is_template' => true,
                'is_premium_template' => true,
                'canvas_rows' => 11,
                'canvas_cols' => 13,
                'path_data' => ['all' => range(0, count($squares) - 1), 'male' => null, 'female' => null],
                'reference_image' => $referenceImage,
                'start_wheel' => ['enabled' => true, 'segments' => $wheel],
            ],
        );

        foreach ($squares as $position => [$color, $text]) {
            [$row, $col] = self::REFERENCE_POS[$position];
            BoardSquare::updateOrCreate(
                ['board_id' => $board->id, 'position' => $position],
                [
                    'text' => str_replace('\\n', "\n", $text),
                    'color' => $color,
                    'grid_row' => $row,
                    'grid_col' => $col,
                ],
            );
        }

        $board->squares()->where('position', '>=', count($squares))->delete();
    }

    private function createTemplate(string $name, string $desc, bool $isPremium, array $squares, string $shape = 'legacy_cross'): void
    {
        if (! $isPremium) {
            $desc = '成人漸進版｜'.$desc;
        }

        /* 三個舊版型留著寫死的座標表 —— 沿用它們的棋盤不該因為這次擴充而變樣。
           其他版型一律從 App\Support\BoardShapes 照格數長出來:內容順序不動,
           只換座標。對不上就直接爆,不要默默少畫幾格(最後幾格內容會掉在棋盤外)。 */
        $legacy = match ($shape) {
            'legacy_square' => [self::SQUARE_POS, 9, 9],
            'legacy_rect' => [self::RECT_POS, 7, 11],
            'legacy_cross' => [self::CROSS_POS, 11, 13],
            default => null,
        };

        if ($legacy !== null) {
            [$gridPos, $canvasRows, $canvasCols] = $legacy;
        } else {
            $layout = BoardShapes::forCount($shape, count($squares));

            if ($layout === null) {
                throw new RuntimeException("版型 {$shape} 產不出 ".count($squares)." 格(棋盤:{$name})");
            }

            $gridPos = array_map(fn ($cell) => [$cell['row'], $cell['col']], $layout['cells']);
            $canvasRows = $layout['rows'];
            $canvasCols = $layout['cols'];
        }

        $referenceImage = $isPremium
            ? ($name === '角色扮演版'
                ? 'images/board-references/couples-flying-chess-v1.jpg'
                : 'images/board-references/couples-flying-chess-v8.jpg')
            : null;

        $board = Board::updateOrCreate(
            ['name' => $name, 'is_template' => true],
            [
                'description' => $desc,
                'is_template' => true,
                'is_premium_template' => $isPremium,
                'canvas_rows' => $canvasRows,
                'canvas_cols' => $canvasCols,
                'path_data' => ['all' => range(0, count($squares) - 1), 'male' => null, 'female' => null],
                'reference_image' => $referenceImage,
                'start_wheel' => in_array($name, ['飲酒派對版', '角色扮演版', '極限派對挑戰版'], true)
                    ? ['enabled' => true, 'segments' => Board::DEFAULT_START_WHEEL]
                    : null,
            ]
        );

        foreach ($squares as $pos => [$idx, $color, $text]) {
            [$row, $col] = $gridPos[$pos] ?? $gridPos[0];
            BoardSquare::updateOrCreate(
                ['board_id' => $board->id, 'position' => $pos],
                [
                    'board_id' => $board->id,
                    'position' => $pos,
                    'text' => str_replace('\n', "\n", $text),
                    'color' => $color,
                    'grid_row' => $row,
                    'grid_col' => $col,
                ]
            );
        }

        $board->squares()->where('position', '>=', count($squares))->delete();
    }
