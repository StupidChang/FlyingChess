    /**
     * Return activity pools for client-side use.
     * Mild and medium are free. Explicit intense activities are only returned
     * after the caller has established premium content access.
     */
    /** 程式碼裡的預設題庫。資料表空的時候用它,也是後台第一次匯入的來源。 */
    /** 資料表空的時候用的預設。沒有 is_paid 可言,所以照舊整級判斷。 */
    private static function defaultPoolsFor(bool $isPremium): array
    {
        $all = self::defaultPools();

        // 預設題庫沒有 is_paid 可言,照舊把原本標著付費的那級留給有權限的人。
        if (! $isPremium) {
            unset($all['intense']);
        }

        return $all;
    }

    public static function defaultPools(): array
    {
        return [
            'mild' => self::MILD_ACTIVITIES,
            'medium' => self::MEDIUM_ACTIVITIES,
            'intense' => self::INTENSE_ACTIVITIES,
        ];
    }

    public static function getActivityPools(bool $isPremium = false): array
    {
        $all = GamePrompt::poolsFor('card_game', $isPremium) ?: self::defaultPoolsFor($isPremium);

        /* 收費是每一題自己的 is_paid,所以過濾在 poolsFor 那一層做完了 ——
           這裡不再整級砍掉 intense:重度裡也可以有免費題目。
           程式碼裡的預設題庫沒有 is_paid 這個概念,所以退回預設時仍然照舊
           把 intense 留給有權限的人。 */
        $pools = [];
        foreach (GamePrompt::LEVEL_ORDER as $level) {
            if (! empty($all[$level])) {
                $pools[$level] = $all[$level];
            }
        }

        return $pools;
    }
