    public static function getSegmentPools(bool $isPremium = false): array
    {
        $pools = self::loadFromDb($isPremium);

        /* 資料表有東西就用資料表。原本要求三級都有才算數,五級之後那個條件
           幾乎不可能成立(新加的兩級一開始是空的),會一路退回寫死的常數,
           後台改的東西就完全看不到。改成「有任何一級就以資料表為準」。 */
        if (array_filter($pools)) {
            return ContentExposure::samplePools($pools);
        }

        // Fallback to hardcoded constants when DB is empty
        $pools = self::defaultPools();

        if (! $isPremium) {
            unset($pools['intense']);
        }

        return ContentExposure::samplePools(ContentTranslations::pools($pools));
    }

    /** 資料表是空的時候用的預設選項(也是翻譯覆蓋率檢查的來源之一) */
    public static function defaultPools(): array
    {
        return self::DEFAULT_POOLS;
    }

    /**
     * 沒有權限的人只拿得到 is_paid = false 的題目。
     *
     * 以前是整級砍掉(unset intense),現在收費是每一題自己的欄位 ——
     * 大膽那級裡也可以有免費的,親密那級裡也可以有付費的。
     */
    private static function loadFromDb(bool $isPremium): array
    {
        $segments = WheelSegment::query()
            ->when(! $isPremium, fn ($q) => $q->where('is_paid', false))
            ->orderBy('id')->get();

        if ($segments->isEmpty()) {
            return [];
        }

        $pools = [];
        foreach ($segments->groupBy('tier') as $tier => $items) {
            $pools[$tier] = $items->pluck('content')->toArray();
        }

        return $pools;
    }
